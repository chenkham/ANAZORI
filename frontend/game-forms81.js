import {initRegistrationConditions} from './registration-conditions.js';
export function initGameForms81(form){
 if(!form)return;const target=form.querySelector('[data-game-form]');
 if(!target){initRegistrationConditions(form);return;}
 const select=form.querySelector('[name=game]'),submit=form.querySelector('[type=submit]');let request=null,dispose=()=>{};
 async function change(){
  request?.abort();request=null;dispose();const game=select.value;submit.disabled=true;target.replaceChildren();
  const status=document.createElement('p');status.className='account-help';status.setAttribute('role','status');status.textContent=game?'Opening your game form…':'Choose a game to open its form.';target.append(status);
  if(!game)return;const current=request=new AbortController();
  try{
   const query=new URLSearchParams({event:target.dataset.event,game,phase:target.dataset.phase});
   const response=await fetch('/api/event-form.php?'+query,{signal:current.signal,credentials:'same-origin'}),result=await response.json();
   if(current!==request)return;if(!response.ok)throw Error(result.error||'This form could not be opened.');
   // This HTML is generated by the same server renderer as the main event form.
   target.innerHTML=result.html;document.querySelector('#interest-title').textContent=result.title;document.querySelector('.dialog-intro').textContent=result.game+' · '+result.intro;submit.firstChild.textContent=result.button+' ';dispose=initRegistrationConditions(form);submit.disabled=false;
  }catch(error){if(error.name==='AbortError'||current!==request)return;status.textContent=error.message+' Please try again.';const retry=document.createElement('button');retry.type='button';retry.className='button button-dark';retry.textContent='Try again';retry.addEventListener('click',change);target.append(retry);}
 }
 select.addEventListener('change',change);form.addEventListener('reset',()=>queueMicrotask(change));change();
}
